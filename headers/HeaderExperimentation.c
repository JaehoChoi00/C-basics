#include "HeaderExperimentation.h"

// Simple integer add function
int add(int a, int b) {
    return a + b;
}

// Simple integer sub function
int sub(int a, int b) {
    return a - b;
}

// Simple integer mul function
int mul(int a, int b) {
    return a * b;
}

// Simple integer div function
int div(int a, int b) {
    return a / b;
}

// Simple integer mod function
int mod(int a, int b) {
    return a % b;
}

